function VFX.Projectile(from, to, color, size, t, arc, trailColor)
	local p = part(Vector3.one * (size or 1), color, CFrame.new(from), Enum.PartType.Ball)
	local a0 = Instance.new("Attachment")
	a0.Position = Vector3.new(0, size and size * 0.4 or 0.4, 0)
	a0.Parent = p
	local a1 = Instance.new("Attachment")
	a1.Position = Vector3.new(0, -(size and size * 0.4 or 0.4), 0)
	a1.Parent = p
	local trail = Instance.new("Trail")
	trail.Attachment0 = a0
	trail.Attachment1 = a1
	trail.Color = ColorSequence.new(trailColor or color)
	trail.Transparency = NumberSequence.new(0.1, 1)
	trail.Lifetime = 0.25
	trail.LightEmission = 1
	trail.LightInfluence = 0
	trail.Texture = Tex.speedline
	trail.FaceCamera = true
	trail.Parent = p
	-- comet glow
	local glowE = Instance.new("ParticleEmitter")
	glowE.Texture = Tex.glow
	glowE.Color = ColorSequence.new(trailColor or color)
	glowE.LightEmission = 1
	glowE.LightInfluence = 0
	glowE.Size = NumberSequence.new((size or 1) * 3, 0)
	glowE.Transparency = NumberSequence.new(0.3, 1)
	glowE.Lifetime = NumberRange.new(0.15, 0.3)
	glowE.Speed = NumberRange.new(0)
	glowE.Rate = 80 * quality()
	glowE.Parent = p
	t = t or 0.25
	local start = os.clock()
	local conn
	conn = game:GetService("RunService").RenderStepped:Connect(function()
		local k = math.min((os.clock() - start) / t, 1)
		local pos = from:Lerp(to, k) + Vector3.new(0, math.sin(k * math.pi) * (arc or 0), 0)
		p.CFrame = CFrame.new(pos)
		if k >= 1 then
			conn:Disconnect()
			p:Destroy()
		end
	end)
end

