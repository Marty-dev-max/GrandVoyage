#!/usr/bin/env python3
"""Pixel icons -> voxel data (v0.25.14, owner: voxel item previews). Reads assets/icons/<name>.png (32x32 art saved
at 8x), keeps opaque pixels and writes src/shared/Config/IconVoxels.lua: per icon a palette of hex colors and 32
run-length rows ('.' = empty, a letter = palette index, an optional count after it). UI.VoxelIcon extrudes them.
   python3 tools/gen_icon_voxels.py
"""
import os, string
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
SRC = os.path.join(ROOT, 'assets', 'icons')
OUT = os.path.join(ROOT, 'src', 'shared', 'Config', 'IconVoxels.lua')
ALPHA = string.ascii_letters + '!#$%&()*+,/:;<=>?@[]^_`{|}~'  # no digits, no '.', no quote/backslash
SKIP = {'graphics', 'audio', 'interface', 'autobattle', 'developer', 'menu', 'anchor', 'auto', 'manual', 'dash',
        'calm', 'flame', 'party', 'stats', 'skills', 'map', 'bag', 'gear', 'whiteflag', 'flag', 'merit', 'paw'}


def encode(im):
    im = im.convert('RGBA').resize((32, 32), Image.NEAREST)
    px = im.load()
    pal, rows = [], []
    for y in range(32):
        cells = []
        for x in range(32):
            r, g, b, a = px[x, y]
            if a < 160:
                cells.append('.')
                continue
            hexc = '%02X%02X%02X' % (r, g, b)
            if hexc not in pal:
                pal.append(hexc)
            i = pal.index(hexc)
            if i >= len(ALPHA):
                raise SystemExit('too many colors')
            cells.append(ALPHA[i])
        toks, i = [], 0
        while i < 32:
            j = i
            while j < 32 and cells[j] == cells[i]:
                j += 1
            toks.append(cells[i] + (str(j - i) if j - i > 1 else ''))
            i = j
        if toks and toks[-1][0] == '.':
            toks.pop()  # trailing empty cells are implied
        rows.append(''.join(toks))
    return pal, rows


def decode_row(s):  # self-check helper (mirrors the Luau decoder)
    out, i = [], 0
    while i < len(s):
        c = s[i]
        i += 1
        d = ''
        while i < len(s) and s[i].isdigit():
            d += s[i]
            i += 1
        out += [c] * (int(d) if d else 1)
    return out


def main():
    names = sorted(n[:-4] for n in os.listdir(SRC) if n.endswith('.png') and not n.startswith(('st_', 'isl_', 'acc_', 'pt_')) and n[:-4] not in SKIP)
    lines = ['-- generated by tools/gen_icon_voxels.py from the pixel icons: do not edit', 'return {']
    for n in names:
        im = Image.open(os.path.join(SRC, n + '.png'))
        pal, rows = encode(im)
        # self-check: decoding gives back the same opaque cells
        src = im.convert('RGBA').resize((32, 32), Image.NEAREST).load()
        for y, r in enumerate(rows):
            cells = decode_row(r)
            for x in range(32):
                filled = x < len(cells) and cells[x] != '.'
                assert filled == (src[x, y][3] >= 160), (n, x, y)
        lines.append('\t%s = { pal = { %s }, rows = { %s } },' % (n, ', '.join('"%s"' % c for c in pal), ', '.join('"%s"' % r for r in rows)))
    lines.append('}')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('wrote', len(names), 'icons,', os.path.getsize(OUT) // 1024, 'KB')


if __name__ == '__main__':
    main()
