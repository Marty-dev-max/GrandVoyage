	e.Rate = 70 * quality()
	e.Parent = att
	local glowE = Instance.new("ParticleEmitter")
	glowE.Texture = Tex.glow
	glowE.Color = ColorSequence.new(c)
	glowE.LightEmission, glowE.LightInfluence = 1, 0
