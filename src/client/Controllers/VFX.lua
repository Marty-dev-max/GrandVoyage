-- Sounds tied to effects (3D positioned)
local fxSounds = {
	Damage = function(d)
		-- the hit you hear is the weapon that landed it: punches thud ("pak"), blades slice, pellets thwack...
		if d.kind == "burn" or d.kind == "poison" then
			return nil
		end
		if d.toPlayer then
			return "PunchHit", d.pos, 0.8
		end
		local w = d.src and VFX.lastWeapon[d.src]
		local snd = ({ Fists = "PunchHit", Knuckles = "PunchHit", Shoes = "PunchHit", Hammer = "PunchHeavy", Sword = "SliceHit", Slingshot = "ShotHit", StormBaton = "PunchHit", MedKit = "PowderPoof" })[w or ""]
		if d.kind == "pet" or d.kind == "cannon" then
			snd = d.kind == "cannon" and "PunchHeavy" or "Hit"
		end
		if d.crit and (snd == "PunchHit" or snd == nil) then
			snd = "PunchHeavy"
		end
		-- v0.25.16 (owner: hits felt thin): a low thump under every hit, a bright crack on top of crits
		Audio.Play("ImpactThump", { pos = d.pos, pitch = 0.9 + math.random() * 0.2, volume = d.crit and 1 or 0.7 })
		-- v0.25.77: a real cut for blades, a heavy sledge thud for the hammer
		if w == "Sword" then
			Audio.Play("SliceCut", { pos = d.pos, pitch = 0.95 + math.random() * 0.15 })
		elseif w == "Hammer" then
			Audio.Play("HammerThud", { pos = d.pos, pitch = 0.85 + math.random() * 0.1, volume = d.crit and 1 or 0.85 })
		end
		if d.crit then
			Audio.Play("Crit", { pos = d.pos })
		end
		return snd or (d.crit and "Crit" or "Hit"), d.pos, d.crit and 1.1 or (0.92 + math.random() * 0.16)
	end,
	BasicAttack = function(d)
		-- the swing itself: a soft whoosh (the impact sound comes on contact)
		if d.weapon == "Slingshot" then
			return nil -- the musket's bang plays on the shot frame (weaponFX.Slingshot)
		end
		local blade = d.weapon == "Sword" or d.weapon == "Hammer"
		return blade and "Slash" or "Whoosh", d.from, blade and 1 or 1.25
	end,
	Skill = function(d)
