"""Upload 3D models (.glb from tools/blender/build_models.py) to Roblox (Open Cloud Assets API, assetType Model)
and write their ids into a Lua config that the game loads with InsertService (server/Services/AssetService.lua).
   ROBLOX_API_KEY=... python3 tools/upload_models.py assets/models3d src/shared/Config/Models.lua [--user 1527424396] [--only A,B]
Already-uploaded files are cached in <folder>/uploaded.json (re-uploaded only if the file changed)."""
import argparse, hashlib, json, os, sys, time, uuid, urllib.request, urllib.error

API = 'https://apis.roblox.com/assets/v1'
KEY = os.environ.get('ROBLOX_API_KEY', '')

def call(method, url, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers={'x-api-key': KEY, **(headers or {})})
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return r.status, json.loads(r.read() or b'{}')
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode('utf-8', 'replace')[:400]

def upload(path, name, user):
    meta = {'assetType': 'Model', 'displayName': f'GV {name}', 'description': f'Grand Voyage model: {name}',
            'creationContext': {'creator': {'userId': str(user)}}}
    b = '----' + uuid.uuid4().hex
    data = open(path, 'rb').read()
    body = (f'--{b}\r\nContent-Disposition: form-data; name="request"\r\nContent-Type: application/json\r\n\r\n{json.dumps(meta)}\r\n'
            f'--{b}\r\nContent-Disposition: form-data; name="fileContent"; filename="{name}.glb"\r\nContent-Type: model/gltf-binary\r\n\r\n').encode() + data + f'\r\n--{b}--\r\n'.encode()
    status, res = call('POST', f'{API}/assets', body, {'Content-Type': f'multipart/form-data; boundary={b}'})
    if status != 200 or not isinstance(res, dict):
        return None, f'{status} {res}'
    op = res.get('path') or res.get('operationId')
    for _ in range(60):
        time.sleep(2)
        status, res = call('GET', f'{API}/{op}' if op.startswith('operations/') else f'{API}/operations/{op}')
        if isinstance(res, dict) and res.get('done'):
            r = res.get('response', {})
            return r.get('assetId'), None if r.get('assetId') else f'no asset id: {res}'
    return None, 'operation timed out'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('folder')
    ap.add_argument('lua')
    ap.add_argument('--user', default='1527424396')
    ap.add_argument('--only', default='')
    a = ap.parse_args()
    only = set(filter(None, a.only.split(',')))
    cache_path = os.path.join(a.folder, 'uploaded.json')
    cache = json.load(open(cache_path)) if os.path.exists(cache_path) else {}
    for f in sorted(os.listdir(a.folder)):
        if not f.endswith('.glb'):
            continue
        name = f[:-4]
        if only and name not in only:
            continue
        digest = hashlib.sha1(open(os.path.join(a.folder, f), 'rb').read()).hexdigest()
        if cache.get(name, {}).get('sha1') == digest:
            print('cached', name, cache[name]['id'])
            continue
        aid, err = upload(os.path.join(a.folder, f), name, a.user)
        if err:
            print('FAIL', name, err)
            continue
        cache[name] = {'id': aid, 'sha1': digest}
        print('OK  ', name, aid)
        json.dump(cache, open(cache_path, 'w'), indent=1, sort_keys=True)
    lines = ['-- Generated by tools/upload_models.py: model name -> Roblox Model asset id (loaded by AssetService). Do not edit by hand.',
             'return {']
    for name in sorted(cache):
        lines.append(f'\t{name} = {cache[name]["id"]},')
    lines.append('}')
    open(a.lua, 'w').write('\n'.join(lines) + '\n')
    print(len(cache), 'ids written to', a.lua)

if __name__ == '__main__':
    main()
