		-- the swing itself: a soft whoosh (the impact sound comes on contact)
		local blade = d.weapon == "Sword" or d.weapon == "Hammer"
		return blade and "Slash" or "Whoosh", d.from, blade and 1 or 1.25
	end,
	Skill = function(d)
		if d.fx == "Heal" or d.fx == "Food" then
			return "Heal", d.from
		end
		if d.fx == "ThunderCall" or d.fx == "Lightning" then
			return "ThunderCrack", d.to or d.from
		end
		if d.fx == "CycloneCall" or d.fx == "Tornado" or d.fx == "Wind" then
			return "WindGust", d.from
		end
		return "MagicCast", d.from
	end,
	LevelUp = function(d)
		return "LevelUp", d.pos
	end,
	MobDeath = function(d)
		-- kill combo: deaths in quick succession climb in pitch
		local now = os.clock()
		VFX.killStreak = (now - (VFX.lastKillAt or 0) < 4) and math.min((VFX.killStreak or 0) + 1, 10) or 0
		VFX.lastKillAt = now
		-- kill streaks only nudge the pitch a little (owner: a rising pitch got shrill when killing fast)
		return d.boss and "BossRoar" or "MonsterDie", d.pos, 1 + math.min(VFX.killStreak, 5) * 0.02
	end,
	ChestOpen = function(d)
		return "ChestOpen", d.pos
	end,
	ChestShake = function(d)
		return "ChestRattle", d.pos
	end,
	Telegraph = function(d)
		return "BossRoar", d.pos
	end,
	Cannonball = function(d)
		return "Cannon", d.from
	end,
	Dash = function(d)
		return "Whoosh", d.from, 1.15
	end,
	WeaponDraw = function(d)
		return d.weapon == "StormBaton" and "AnvilClang" or "Equip", d.pos, d.weapon == "StormBaton" and 1.7 or 1
	end,
	Splash = function(d)
		return "Splash", d.pos
	end,
	Explosion = function(d)
		return "Explosion", d.pos
	end,
	ShipHit = function(d)
		return "ShipHit", d.pos
	end,
	ShipSink = function(d)
		return "Explosion", d.pos
	end,
	SeaKingRise = function(d)
		return "BossRoar", d.pos
	end,
	RefineSuccess = function(d)
		return "RefineSuccess", d.pos
	end,
	SerpentBite = function(d)
		return "PunchHeavy", d.to, 0.7
	end,
	SerpentSpit = function(d)
		return "Splash", d.from, 0.8
	end,
	SerpentRise = function(d)
		return "WaterPlunge", d.pos, 0.6
	end,
	ShipDebris = function(d)
		return "ShipHit", d.pos, 0.9
	end,
	SeastoneSeal = function(d)
		local c = d.char
		local r = typeof(c) == "Instance" and c:FindFirstChild("HumanoidRootPart")
		return "RefineFail", r and r.Position or nil, 1.2
	end,
	Knockback = function(d)
		local m = d.model
		local p = typeof(m) == "Instance" and m.PrimaryPart
		return "FinisherBoom", p and p.Position or nil, d.big and 0.8 or 1
	end,
	MobAlert = function(d)
		local m = d.model
		local p = typeof(m) == "Instance" and m.PrimaryPart
		return "MobAlert", p and p.Position or nil
	end,
}

function VFX.Start()
	Net.OnFX(function(kind, data)
		local h = handlers[kind]
		local snd = fxSounds[kind]
		if snd and type(data) == "table" then
			local ok, name, pos, pitch = pcall(snd, data)
			if ok and name then
				Audio.Play(name, { pos = pos, pitch = pitch })
			end
		end
		if kind == "Damage" and not Settings.Values.damageNumbers then
			return
		end
		if h and type(data) == "table" then
			local ok, err = pcall(h, data)
			if not ok then
				warn("[VFX]", kind, err)
			end
		end
	end)
end

VFX.Handlers = handlers
return VFX
