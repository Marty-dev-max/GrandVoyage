function VFX.Beam(from, to, c, width, t, texture)
	t = t or 0.3
	local h0 = part(Vector3.new(0.2, 0.2, 0.2), c, CFrame.new(from), nil, nil, 1)
	local h1 = part(Vector3.new(0.2, 0.2, 0.2), c, CFrame.new(to), nil, nil, 1)
	local a0, a1 = Instance.new("Attachment"), Instance.new("Attachment")
	a0.Parent, a1.Parent = h0, h1
	local beam = Instance.new("Beam")
	beam.Attachment0, beam.Attachment1 = a0, a1
	beam.Texture = texture or Tex.lightning
	beam.TextureMode = Enum.TextureMode.Stretch
	beam.TextureSpeed = 4
	beam.LightEmission = 1
	beam.LightInfluence = 0
	beam.FaceCamera = true
	beam.Width0, beam.Width1 = (width or 1) * 3, (width or 1) * 3
	beam.Color = color(c)
	beam.Parent = h0
	local start = os.clock()
	local conn
	conn = game:GetService("RunService").RenderStepped:Connect(function()
		local k = (os.clock() - start) / t
		beam.Transparency = NumberSequence.new(math.clamp(k, 0, 1))
		if k >= 1 then
			conn:Disconnect()
		end
	end)
	Debris:AddItem(h0, t + 0.1)
	Debris:AddItem(h1, t + 0.1)
end

function VFX.Aura(char, c, t, heal)
	local root = char and char:FindFirstChild("HumanoidRootPart")
	if not root then
		return
	end
	t = t or 0.9
	local feet = root.Position - Vector3.new(0, 2.8, 0)
	VFX.Ring(feet, 5, c, 0.5)
	-- soft ground glow + three rings that rise up the body (buff "charging" look)
	emit(feet + Vector3.new(0, 0.2, 0), flat({ Texture = Tex.glow, Color = ColorSequence.new(c), Size = seq(9, 11), Transparency = seq(0.35, 1), Lifetime = NumberRange.new(t), Fixed = true }), 1, t)
	for i = 0, 2 do
		task.delay(i * 0.12, function()
			emit(feet + Vector3.new(0, 0.3, 0), { Texture = Tex.ring, Color = color(c), Orientation = Enum.ParticleOrientation.VelocityPerpendicular, EmissionDirection = Enum.NormalId.Top, Speed = NumberRange.new(9), SpreadAngle = Vector2.new(0, 0), Drag = 1.5, Size = seq(5.5, 3.5), Transparency = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0.2), NumberSequenceKeypoint.new(0.7, 0.4), NumberSequenceKeypoint.new(1, 1) }), Lifetime = NumberRange.new(0.55), Fixed = true }, 1, 0.6)
		end)
	end
	if heal then
		emit(root.Position, { Texture = Tex.plus, Color = ColorSequence.new(Color3.fromRGB(200, 255, 210), c), Size = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0), NumberSequenceKeypoint.new(0.15, 1.3), NumberSequenceKeypoint.new(1, 0.6) }), Transparency = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0), NumberSequenceKeypoint.new(0.7, 0.1), NumberSequenceKeypoint.new(1, 1) }), Lifetime = NumberRange.new(0.8, 1.2), Speed = NumberRange.new(3, 6), SpreadAngle = Vector2.new(50, 50), EmissionDirection = Enum.NormalId.Top, Shape = Enum.ParticleEmitterShape.Sphere, Drag = 1, Acceleration = Vector3.new(0, 2, 0) }, 10, 1.3)
	end
	-- a burst of rising glow motes and sparkles that follow the character
	local att = Instance.new("Attachment")
	att.Position = Vector3.new(0, -2, 0)
	att.Parent = root
	local function mk(props, rate)
		local e = Instance.new("ParticleEmitter")
		e.LightInfluence = 0
		e.LightEmission = 1
		e.Rate = rate * quality()
		for k, v in pairs(props) do
			e[k] = v
		end
		e.Parent = att
		return e
	end
	mk({ Texture = Tex.glow, Color = ColorSequence.new(c), Size = seq(2.2, 0), Transparency = seq(0.2, 1), Lifetime = NumberRange.new(0.5, 0.9), Speed = NumberRange.new(5, 9), SpreadAngle = Vector2.new(25, 25), Shape = Enum.ParticleEmitterShape.Cylinder, ShapeStyle = Enum.ParticleEmitterShapeStyle.Surface }, 60)
	mk({ Texture = Tex.sparkle, Color = ColorSequence.new(c:Lerp(Color3.new(1, 1, 1), 0.5)), Size = seq(1.2, 0), Lifetime = NumberRange.new(0.4, 0.7), Speed = NumberRange.new(6, 12), SpreadAngle = Vector2.new(30, 30), RotSpeed = NumberRange.new(-200, 200) }, 25)
	task.delay(t, function()
		for _, e in ipairs(att:GetChildren()) do
			e.Enabled = false
		end
		Debris:AddItem(att, 1)
	end)
end

function VFX.Splash(pos, size)
	Voxels.Blocks(pos, { count = 6 + math.floor((size or 4) * 1.5), colors = { Color3.fromRGB(120, 200, 255), Color3.fromRGB(230, 248, 255), Color3.fromRGB(60, 150, 230) }, size = math.clamp((size or 4) * 0.08, 0.25, 0.9), speed = (size or 4) * 1.6, up = 14 + (size or 4), collide = false, life = 0.6, material = Enum.Material.Glass })
	size = size or 10
	local base = Vector3.new(pos.X, 0.2, pos.Z)
	local col = part(Vector3.new(size * 0.5, 1, size * 0.5), Color3.fromRGB(230, 250, 255), CFrame.new(base), Enum.PartType.Cylinder, Enum.Material.SmoothPlastic, 0.1)
	col.CFrame = CFrame.new(base) * CFrame.Angles(0, 0, math.pi / 2)
	col.Size = Vector3.new(1, size * 0.5, size * 0.5)
	tween(col, 0.35, { Size = Vector3.new(size * 1.6, size * 0.35, size * 0.35), CFrame = CFrame.new(base + Vector3.new(0, size * 0.8, 0)) * CFrame.Angles(0, 0, math.pi / 2) })
	task.delay(0.35, function()
		fadeOut(col, 0.4)
	end)
	VFX.Ring(base, size, Color3.fromRGB(255, 255, 255), 0.6, 0.3)
	VFX.Sparks(base + Vector3.new(0, 1, 0), Color3.fromRGB(200, 240, 255), 10, size)
end

function VFX.Explosion(pos, radius)
	Voxels.Blocks(pos, { count = 10 + math.floor((radius or 8) * 1.2), colors = { Color3.fromRGB(255, 200, 80), Color3.fromRGB(255, 120, 40), Color3.fromRGB(60, 50, 46), Color3.fromRGB(120, 100, 90) }, size = math.clamp((radius or 8) * 0.08, 0.35, 1.4), speed = (radius or 8) * 2, up = 16, life = 0.9 })
	if custom("Explosion", CFrame.new(pos)) then
		return
	end
	VFX.Burst(pos, radius * 0.9, Color3.fromRGB(255, 180, 60), 0.3)
	VFX.Flames(pos, Color3.fromRGB(255, 120, 40), 18, radius * 0.7)
	VFX.Smoke(pos + Vector3.new(0, 2, 0), Color3.fromRGB(90, 85, 85), 10, radius * 0.6)
	VFX.Ring(pos - Vector3.new(0, 1.5, 0), radius * 1.2, Color3.fromRGB(255, 200, 120), 0.45)
	VFX.Crack(pos - Vector3.new(0, 1.8, 0), radius * 0.8)
end

