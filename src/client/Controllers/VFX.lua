local function part(size, color, cf, shape, material, transparency)
	local p = Instance.new("Part")
	p.Anchored = true
	p.CanCollide = false
	p.CanQuery = false
	p.CanTouch = false
	p.CastShadow = false
	p.Size = size
	p.Color = color
	p.CFrame = cf
	p.Material = material or Enum.Material.Neon
	p.Transparency = transparency or 0
	if shape == Enum.PartType.Ball then
		-- voxel style: a sphere becomes a cube (a little smaller, so it reads the same size)
		p.Size = size * 0.85
	elseif shape == Enum.PartType.Cylinder then
		-- rings / discs / pillars become flat square slabs (cylinder axis X -> slab is thin along X)
		p.Size = Vector3.new(size.X, size.Y * 0.88, size.Z * 0.88)
	end
	p.Parent = fxFolder
	return p
end

local function tween(inst, t, props, style)
	local tw = TweenService:Create(inst, TweenInfo.new(t, style or Enum.EasingStyle.Quad, Enum.EasingDirection.Out), props)
	tw:Play()
	return tw
end

local function fadeOut(p, t, grow)
	local props = { Transparency = 1 }
	if grow then
		props.Size = p.Size * grow
	end
	tween(p, t, props)
	Debris:AddItem(p, t + 0.05)
end

local function custom(name, cf)
	local assets = ReplicatedStorage:FindFirstChild("Assets")
	local fx = assets and assets:FindFirstChild("VFX") and assets.VFX:FindFirstChild(name)
	if fx then
		local c = fx:Clone()
		if c:IsA("Model") then
			c:PivotTo(cf)
		elseif c:IsA("BasePart") then
			c.CFrame = cf
		end
		c.Parent = fxFolder
		for _, e in ipairs(c:GetDescendants()) do
			if e:IsA("ParticleEmitter") then
				e:Emit(e:GetAttribute("EmitCount") or 20)
			end
		end
		Debris:AddItem(c, 4)
		return true
	end
	return false
end

-- ===== particle toolkit (Anime Vanguards-style: textured, additive, bloomy) =====
-- Textures are generated by tools/gen_vfx.py and uploaded by tools/upload_images.py (Config/Textures).
local function quality()
	local q = Settings.Values and Settings.Values.quality
	return (q == "Low" and 0.35) or (q == "Medium" and 0.7) or (q == "Ultra" and 1.3) or 1
end

local function seq(a, b)
	return NumberSequence.new(a, b)
end

-- Emit `count` particles at `pos` from a temporary anchored host. props = ParticleEmitter properties.
local function emit(pos, props, count, life, host)
	local h = host or part(Vector3.new(0.2, 0.2, 0.2), Color3.new(1, 1, 1), CFrame.new(pos), nil, nil, 1)
	local e = Instance.new("ParticleEmitter")
	e.Rate = 0
	e.LightInfluence = 0
	e.LightEmission = 1
	e.ZOffset = 1
	for k, v in pairs(props) do
		if k ~= "Fixed" then
			e[k] = v
		end
	end
	if PIXEL[e.Texture] and e.Orientation == Enum.ParticleOrientation.FacingCamera and e.Texture ~= Tex.slash then
		-- square pixels stay square: no random spin (slashes keep their aimed rotation)
		e.RotSpeed = NumberRange.new(0)
		if e.Rotation.Max - e.Rotation.Min >= 90 then
			e.Rotation = NumberRange.new(0)
		end
	end
	e.Parent = h
	e:Emit(math.max(1, math.floor(count * (props.Fixed and 1 or quality()) + 0.5)))
	if not host then
		Debris:AddItem(h, life + 0.3)
	end
	return e, h
end

local function color(c)
	return ColorSequence.new(c:Lerp(Color3.new(1, 1, 1), 0.35), c)
end

-- flat on the ground: particles moving straight up with VelocityPerpendicular orientation lie flat
